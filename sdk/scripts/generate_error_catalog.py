"""Generate SDK error mappings from the supported public error catalog."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONNECT_STATUS = {
    "invalid_argument": 400,
    "failed_precondition": 400,
    "permission_denied": 403,
    "resource_exhausted": 429,
    "unavailable": 503,
}
DOMAINS = {"openeight.access", "openeight.govern", "openeight.identity"}


def unique_object(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError(f"Duplicate catalog field: {key}")
        value[key] = item
    return value


def validate_catalog(value):
    if not isinstance(value, dict) or set(value) != {"format_version", "errors"}:
        raise ValueError("Expected format_version and errors")
    if type(value["format_version"]) is not int or value["format_version"] != 1:
        raise ValueError("Unsupported catalog format")
    records = value["errors"]
    if not isinstance(records, list) or not records:
        raise ValueError("Expected a nonempty error list")
    seen = set()
    for row in records:
        if not isinstance(row, dict) or set(row) != {"reason", "domain", "connect_code", "http_status"}:
            raise ValueError("Expected reason, domain, connect_code and http_status only")
        reason = row["reason"]
        if not isinstance(reason, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,127}", reason):
            raise ValueError("Invalid public reason")
        if reason in seen:
            raise ValueError(f"Duplicate public reason: {reason}")
        seen.add(reason)
        if not isinstance(row["domain"], str) or row["domain"] not in DOMAINS:
            raise ValueError("Unsupported public domain")
        code, status = row["connect_code"], row["http_status"]
        if not isinstance(code, str) or type(status) is not int or CONNECT_STATUS.get(code) != status:
            raise ValueError("HTTP status does not match the supported Connect code")
    return sorted(records, key=lambda row: row["reason"])


def render_outputs(value):
    rows = validate_catalog(value)
    python = '# Generated by scripts/generate_error_catalog.py; do not edit.\n\nERROR_DETAILS = {\n'
    for row in rows:
        python += f'    {json.dumps(row["reason"])}: ({json.dumps(row["domain"])}, {row["http_status"]}, {json.dumps(row["connect_code"])}),\n'
    python += '}\n\nGOVERNANCE_REASONS = {\n    reason: (status, code) for reason, (_, status, code) in ERROR_DETAILS.items()\n}\n'
    typescript = '// Generated by scripts/generate_error_catalog.py; do not edit.\n'
    typescript += 'export const errorDetails:Readonly<Record<string,readonly [string,number,string]>> = Object.freeze({\n'
    for row in rows:
        typescript += f'  {json.dumps(row["reason"])}:Object.freeze([{json.dumps(row["domain"])},{row["http_status"]},{json.dumps(row["connect_code"])}] as const),\n'
    typescript += '});\n'
    return {
        "python/openeight/_error_catalog.py": python,
        "typescript/src/error-catalog.ts": typescript,
    }


def generate(root, check=False):
    value = json.loads((root / "contracts/errors.json").read_text(), object_pairs_hook=unique_object)
    outputs = render_outputs(value)
    if check:
        stale = [name for name, contents in outputs.items() if not (root / name).is_file() or (root / name).read_text() != contents]
        if stale:
            raise ValueError("Generated error mappings are stale: " + ", ".join(stale))
    else:
        for name, contents in outputs.items():
            (root / name).write_text(contents)
    return len(value["errors"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        count = generate(ROOT, check=args.check)
    except (ValueError, OSError) as error:
        parser.exit(1, f"{error}\n")
    print(f'{count} public error mappings {"verified" if args.check else "generated"}')


if __name__ == "__main__":
    main()
